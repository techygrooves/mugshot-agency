/**
 * make-hostinger.mjs — prepares a finished build in dist/ for Hostinger
 * (LiteSpeed/Apache shared hosting), then zips it for upload.
 *
 *   npm run package:hostinger      (builds first, then runs this)
 *
 * Hostinger ignores public/_headers, so this translates it into .htaccess:
 *   - dist/.htaccess: HTTPS redirect, redirect to the canonical host (only
 *     once site.urlConfirmed is true), custom 404, no directory listings,
 *     security headers + CSP from _headers, HTML revalidation, compression
 *   - dist/_astro/.htaccess: one-year immutable caching for fingerprinted files
 * and removes dist/_headers (meaningless on Apache).
 *
 * Upload the CONTENTS of dist/ (or of hostinger-site.zip) into public_html.
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { site } from '../src/config/site.ts';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DIST = path.join(ROOT, 'dist');
const ZIP = path.join(ROOT, 'hostinger-site.zip');

/** Parses the Netlify/Cloudflare _headers format into { pattern: { name: value } }. */
function parseHeaders(text) {
  const rules = {};
  let current = null;
  for (const line of text.split('\n')) {
    if (!line.trim() || line.trim().startsWith('#')) continue;
    if (!/^\s/.test(line)) rules[(current = line.trim())] = {};
    else {
      const i = line.indexOf(':');
      rules[current][line.slice(0, i).trim()] = line.slice(i + 1).trim();
    }
  }
  return rules;
}

const rules = parseHeaders(await fs.readFile(path.join(DIST, '_headers'), 'utf8'));
const global = { ...rules['/*'] };
// On shared hosting, subdomains (mail, webmail, staging) may not all have SSL;
// includeSubDomains would lock them out. Scope HSTS to this host only.
if (global['Strict-Transport-Security']) global['Strict-Transport-Security'] = 'max-age=31536000';

const quote = (v) => `"${v.replace(/"/g, '\\"')}"`;
const host = new URL(site.url).host;
const bare = host.replace(/^www\./, '');

const htaccess = `# Generated by scripts/make-hostinger.mjs from public/_headers — do not edit by hand.
# National Reputation Defense — Hostinger (LiteSpeed/Apache)

Options -Indexes
DirectoryIndex index.html
ErrorDocument 404 /404.html

<IfModule mod_rewrite.c>
  RewriteEngine On

  # Always HTTPS (Hostinger terminates SSL; check both the flag and the proxy header).
  RewriteCond %{HTTPS} !=on
  RewriteCond %{HTTP:X-Forwarded-Proto} !https
  RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [L,R=301]
${
  site.urlConfirmed
    ? `
  # One canonical host: ${host}
  RewriteCond %{HTTP_HOST} !^${host.replace(/\./g, '\\.')}$ [NC]
  RewriteCond %{HTTP_HOST} ^(www\\.)?${bare.replace(/\./g, '\\.')}$ [NC]
  RewriteRule ^ https://${host}%{REQUEST_URI} [L,R=301]
`
    : `
  # Host redirect disabled: site.urlConfirmed is false (domain not confirmed).
`
}
  # Folders get their trailing slash in one HTTPS hop (instead of Apache's
  # DirectorySlash, which can redirect to http:// first).
  RewriteCond %{REQUEST_FILENAME} -d
  RewriteRule ^(.*[^/])$ https://%{HTTP_HOST}/$1/ [L,R=301]

  # Hide dotfiles (except /.well-known for SSL validation).
  RewriteRule (^|/)\\.(?!well-known/) - [F]
</IfModule>

<IfModule mod_headers.c>
${Object.entries(global)
  .map(([name, value]) => `  Header always set ${name} ${quote(value)}`)
  .join('\n')}

  # Pages revalidate on every visit so updates show immediately.
  <FilesMatch "\\.(html|xml|txt|webmanifest)$">
    Header set Cache-Control "public, max-age=0, must-revalidate"
  </FilesMatch>
  # Icons and share images: cache for a week.
  <FilesMatch "\\.(png|svg|ico)$">
    Header set Cache-Control "public, max-age=604800"
  </FilesMatch>
</IfModule>

<IfModule mod_mime.c>
  AddType application/manifest+json .webmanifest
  AddType font/woff2 .woff2
  AddType image/svg+xml .svg
</IfModule>

<IfModule mod_deflate.c>
  AddOutputFilterByType DEFLATE text/html text/css text/javascript application/javascript application/json application/xml image/svg+xml application/manifest+json
</IfModule>
`;

const assetCache = rules['/_astro/*']?.['Cache-Control'] ?? 'public, max-age=31536000, immutable';
const assetsHtaccess = `# Generated by scripts/make-hostinger.mjs — fingerprinted build assets never change.
<IfModule mod_headers.c>
  Header set Cache-Control ${quote(assetCache)}
</IfModule>
`;

await fs.writeFile(path.join(DIST, '.htaccess'), htaccess);
await fs.writeFile(path.join(DIST, '_astro', '.htaccess'), assetsHtaccess);
await fs.rm(path.join(DIST, '_headers'), { force: true });
console.log('make-hostinger: wrote dist/.htaccess and dist/_astro/.htaccess, removed dist/_headers');
if (!site.urlConfirmed) {
  console.log('make-hostinger: ⚠ site.urlConfirmed is false — robots.txt blocks all crawlers and no host redirect is set.');
}

// Zip the contents of dist/ (not the folder itself) for File Manager upload.
await fs.rm(ZIP, { force: true });
try {
  execFileSync('zip', ['-qr', ZIP, '.'], { cwd: DIST });
  const { size } = await fs.stat(ZIP);
  console.log(`make-hostinger: ${path.relative(ROOT, ZIP)} (${(size / 1024 / 1024).toFixed(1)} MB) — upload and extract into public_html`);
} catch {
  console.log('make-hostinger: `zip` not available; upload the contents of dist/ instead.');
}
